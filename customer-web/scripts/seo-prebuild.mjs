/**
 * SEO pre-build step (runs automatically via the `prebuild` npm script, and
 * on demand with `npm run seo:assets`).
 *
 * Produces three things from LIVE API data — nothing here is hardcoded:
 *   1. index.html   — the default <head> (title, description, canonical, OG,
 *                     Twitter) plus the site-wide Organization / WebSite /
 *                     LocalBusiness JSON-LD, and a <noscript> summary, all
 *                     visible to crawlers that never run JavaScript
 *                     (WhatsApp and Facebook link previews, most AI crawlers).
 *   2. public/robots.txt  — crawlable, AI-crawler friendly, private pages blocked.
 *   3. public/sitemap.xml — every real product and category URL.
 *
 * Failure behaviour (deliberate — a storefront build must not be held hostage
 * by a sleeping API): if the catalogue cannot be fetched, the script prints a
 * loud warning, leaves the previously generated index.html block untouched, and
 * writes a CORE sitemap (home, shop, combos, static pages) instead of failing.
 * Pass --strict to turn that into a hard build failure instead.
 */

import fs from 'node:fs';
import path from 'node:path';

import { buildPageSeo, resolveBusiness, plainText, formatInr } from '../src/seo/schema.js';
import { buildPath } from '../src/seo/routes.js';
import {
  ROOT,
  siteOrigin,
  fetchCatalogue,
  pickDefaultImage,
  renderHeadBlock,
  replaceMarkedBlock,
  escapeHtml,
  log,
  warnBlock
} from './seo-shared.mjs';

const STRICT = process.argv.includes('--strict');
const MODE = process.argv.includes('--dev') ? 'development' : 'production';

/** Category slugs the storefront renders as the combos view — one canonical URL. */
const COMBO_ALIAS_SLUGS = new Set(['combos', 'combo-offers', 'gift-boxes']);

const STATIC_SITEMAP_PAGES = [
  { page: 'home', priority: '1.0', changefreq: 'daily' },
  { page: 'shop', priority: '0.9', changefreq: 'daily' },
  { page: 'shop', params: { view: 'combos' }, priority: '0.9', changefreq: 'daily' },
  { page: 'category-menu', priority: '0.6', changefreq: 'weekly' },
  { page: 'about', priority: '0.5', changefreq: 'monthly' },
  { page: 'contact', priority: '0.5', changefreq: 'monthly' },
  { page: 'safety', priority: '0.5', changefreq: 'monthly' },
  { page: 'shipping-policy', priority: '0.4', changefreq: 'yearly' },
  { page: 'terms', priority: '0.3', changefreq: 'yearly' },
  { page: 'privacy', priority: '0.3', changefreq: 'yearly' },
  { page: 'track-order', priority: '0.4', changefreq: 'monthly' }
];

/**
 * The public origin. Configured explicitly via VITE_SITE_URL; otherwise derived
 * from the owner's own `Store.Email` domain (still real, owner-controlled data —
 * never a guessed domain). Empty when neither is usable.
 */
function resolveOrigin(settings) {
  const configured = siteOrigin(MODE);
  if (configured) return { origin: configured, source: 'VITE_SITE_URL' };

  const email = String(settings?.['Store.Email'] || '').trim();
  const domain = email.includes('@') ? email.split('@').pop().trim().toLowerCase() : '';
  if (domain && /^[a-z0-9-]+(\.[a-z0-9-]+)+$/.test(domain) && !/^(example|test|localhost)\./.test(domain)) {
    return { origin: `https://${domain}`, source: `Store.Email domain (${domain})` };
  }
  return { origin: '', source: 'unresolved' };
}

/* ── robots.txt ──────────────────────────────────────────────────────────── */

const PRIVATE_PATHS = [
  '/cart',
  '/checkout',
  '/account',
  '/orders',
  '/wishlist',
  '/login',
  '/register',
  '/forgot-password',
  '/verify-otp',
  '/reset-password',
  '/order-confirmed',
  '/payment/',
  '/track/'
];

/**
 * Generative-engine crawlers the owner explicitly wants reading the catalogue.
 * Each gets the same rules as everyone else — full catalogue, no private pages.
 */
const AI_CRAWLERS = [
  'GPTBot',
  'OAI-SearchBot',
  'ChatGPT-User',
  'ClaudeBot',
  'anthropic-ai',
  'Claude-Web',
  'Claude-SearchBot',
  'PerplexityBot',
  'Perplexity-User',
  'Google-Extended',
  'CCBot',
  'Applebot-Extended',
  'meta-externalagent',
  'Amazonbot',
  'cohere-ai'
];

function renderRobots(origin, business) {
  // Search (`?q=`) and sort (`?sort=`) variants are handled with `noindex` and a
  // canonical rather than a Disallow — a crawler has to be able to FETCH those
  // pages to see either signal, so blocking them here would be self-defeating.
  const rules = ['Allow: /', ...PRIVATE_PATHS.map((p) => `Disallow: ${p}`)].join('\n');

  const groups = [`User-agent: *\n${rules}`, ...AI_CRAWLERS.map((agent) => `User-agent: ${agent}\n${rules}`)];

  return [
    `# robots.txt for ${business.name}`,
    '# Generated by scripts/seo-prebuild.mjs — edit that script, not this file.',
    '#',
    '# AI / generative engines are welcome: the product catalogue below is public',
    '# and intended to be readable by answer engines as well as search engines.',
    '',
    groups.join('\n\n'),
    '',
    origin ? `Sitemap: ${origin}/sitemap.xml` : '# Sitemap: not emitted — no site origin configured (set VITE_SITE_URL).',
    ''
  ].join('\n');
}

/* ── sitemap.xml ─────────────────────────────────────────────────────────── */

const urlEntry = (origin, urlPath, { priority, changefreq, lastmod } = {}) =>
  [
    '  <url>',
    `    <loc>${escapeHtml(`${origin}${urlPath}`)}</loc>`,
    lastmod ? `    <lastmod>${lastmod}</lastmod>` : '',
    changefreq ? `    <changefreq>${changefreq}</changefreq>` : '',
    priority ? `    <priority>${priority}</priority>` : '',
    '  </url>'
  ]
    .filter(Boolean)
    .join('\n');

/** ProductDto/CategoryDto expose no updatedAt, so lastmod is only emitted when a
 *  date actually arrives from the API — never faked from the build clock. */
const lastmodOf = (entity) => {
  const raw = entity?.updatedAt || entity?.modifiedAt || entity?.createdAt;
  if (!raw) return undefined;
  const date = new Date(raw);
  return Number.isNaN(date.getTime()) ? undefined : date.toISOString().slice(0, 10);
};

function renderSitemap(origin, data) {
  const entries = STATIC_SITEMAP_PAGES.map((entry) =>
    urlEntry(origin, buildPath(entry.page, entry.params || {}), entry)
  );

  const categories = (data.categories || []).filter(
    (c) => c.isActive !== false && Number(c.productCount) > 0 && !COMBO_ALIAS_SLUGS.has(String(c.slug).toLowerCase())
  );
  categories.forEach((category) => {
    entries.push(
      urlEntry(origin, buildPath('shop', { category: category.slug }), {
        priority: '0.8',
        changefreq: 'weekly',
        lastmod: lastmodOf(category)
      })
    );
  });

  const products = (data.products || []).filter((p) => p.isActive !== false);
  products.forEach((product) => {
    entries.push(
      urlEntry(origin, buildPath('product-detail', { slug: product.slug }), {
        priority: '0.8',
        changefreq: 'weekly',
        lastmod: lastmodOf(product)
      })
    );
  });

  const xml = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    entries.join('\n'),
    '</urlset>',
    ''
  ].join('\n');

  return { xml, counts: { categories: categories.length, products: products.length, total: entries.length } };
}

/* ── <noscript> summary ──────────────────────────────────────────────────── */

function renderNoscript(business, data, origin) {
  const categories = (data.categories || [])
    .filter((c) => c.isActive !== false && Number(c.productCount) > 0)
    .slice(0, 12);
  const products = (data.products || []).filter((p) => p.isActive !== false).slice(0, 12);

  const addressLine = business.address
    ? [business.address.streetAddress, business.address.addressLocality, business.address.addressRegion, business.address.postalCode]
        .filter(Boolean)
        .join(', ')
    : '';

  const contactBits = [
    business.telephone ? `Phone: ${escapeHtml(business.telephone)}` : '',
    business.email ? `Email: ${escapeHtml(business.email)}` : '',
    addressLine ? `Address: ${escapeHtml(addressLine)}` : ''
  ].filter(Boolean);

  return [
    '<noscript>',
    '      <div style="max-width:44rem;margin:0 auto;padding:2rem 1.25rem;font-family:system-ui,sans-serif;line-height:1.6;color:#1e293b">',
    `        <h1 style="font-size:1.6rem;margin:0 0 .5rem">${escapeHtml(business.name)}</h1>`,
    `        <p><strong>${escapeHtml(business.tagline || 'Sivakasi fireworks, delivered across India')}.</strong> ${escapeHtml(
      business.name
    )} sells Sivakasi-made crackers, sparklers, flower pots, aerial shots, gift boxes and combo packs online, with delivery across India.</p>`,
    categories.length
      ? `        <h2 style="font-size:1.1rem;margin:1.5rem 0 .5rem">Shop by category</h2>\n        <ul>${categories
          .map((c) => `<li><a href="${escapeHtml(`${origin}${buildPath('shop', { category: c.slug })}`)}">${escapeHtml(c.name)}</a></li>`)
          .join('')}</ul>`
      : '',
    products.length
      ? `        <h2 style="font-size:1.1rem;margin:1.5rem 0 .5rem">Popular products</h2>\n        <ul>${products
          .map(
            (p) =>
              `<li><a href="${escapeHtml(`${origin}${buildPath('product-detail', { slug: p.slug })}`)}">${escapeHtml(p.name)}</a>${
                Number(p.price) > 0 ? ` — ${escapeHtml(formatInr(p.price))}` : ''
              }${p.shortDescription ? ` — ${escapeHtml(plainText(p.shortDescription))}` : ''}</li>`
          )
          .join('')}</ul>`
      : '',
    contactBits.length ? `        <h2 style="font-size:1.1rem;margin:1.5rem 0 .5rem">Contact</h2>\n        <p>${contactBits.join(' · ')}</p>` : '',
    '        <p style="margin-top:1.5rem;color:#64748b;font-size:.9rem">This store needs JavaScript for the full shopping experience. Please enable it to browse, add to cart and check out.</p>',
    '      </div>',
    '    </noscript>'
  ]
    .filter(Boolean)
    .join('\n');
}

/* ── main ────────────────────────────────────────────────────────────────── */

async function main() {
  const data = await fetchCatalogue(MODE);
  const { origin, source } = resolveOrigin(data.settings);
  const business = resolveBusiness(data.settings);
  const defaultImage = pickDefaultImage(data);

  if (!data.ok) {
    const message = [
      `Could not read the catalogue API: ${data.reason}.`,
      'Set VITE_SEO_API_BASE_URL to an absolute API base URL reachable from the build machine',
      '(.env.production sets VITE_API_BASE_URL to the browser-relative "/api/v1", which Node cannot fetch).',
      'Falling back to a CORE sitemap (home / shop / combos / static pages) with NO product or category URLs,',
      'and leaving the existing index.html SEO block untouched.'
    ];
    if (STRICT) {
      warnBlock('SEO BUILD FAILED (--strict)', message);
      process.exit(1);
    }
    warnBlock('SEO BUILD DEGRADED', message);
  }

  if (!origin) {
    warnBlock('NO SITE ORIGIN', [
      'Neither VITE_SITE_URL nor a usable Store.Email domain is available.',
      'sitemap.xml cannot be written (sitemaps require absolute URLs) and robots.txt will omit its Sitemap line.',
      'Set VITE_SITE_URL=https://your-live-domain in .env.production (or in the Render environment).'
    ]);
  } else {
    log(`site origin: ${origin}  (source: ${source})`);
  }

  if (business.warnings.length) {
    warnBlock('BUSINESS IDENTITY PLACEHOLDERS DETECTED (GET /settings/public)', [
      ...business.warnings,
      'These values are published as structured data (Organization / LocalBusiness) once they are real.',
      'Fix them in the admin Settings screen — no code change or redeploy is needed for the runtime metadata.'
    ]);
  }

  /* 1 — index.html */
  const indexPath = path.join(ROOT, 'index.html');
  let html = fs.readFileSync(indexPath, 'utf8');

  // index.html owns no <title>/<meta> of its own — this block is the only one,
  // so it is always written (a missing origin just yields root-relative URLs).
  const seo = buildPageSeo({
    page: 'home',
    params: {},
    matched: true,
    origin,
    settings: data.settings,
    categories: data.categories,
    defaultImage
  });
  html = replaceMarkedBlock(html, 'SEO', renderHeadBlock(seo, origin), '</head>');
  html = replaceMarkedBlock(html, 'NOSCRIPT', `    ${renderNoscript(business, data, origin)}`, '</body>', '    ');
  fs.writeFileSync(indexPath, html, 'utf8');
  log(`index.html head + noscript updated (og:image: ${defaultImage ? 'from live data' : 'none available'})`);

  /* 2 — robots.txt */
  const publicDir = path.join(ROOT, 'public');
  fs.mkdirSync(publicDir, { recursive: true });
  fs.writeFileSync(path.join(publicDir, 'robots.txt'), renderRobots(origin, business), 'utf8');
  log('public/robots.txt written');

  /* 3 — sitemap.xml */
  if (origin) {
    const { xml, counts } = renderSitemap(origin, data);
    fs.writeFileSync(path.join(publicDir, 'sitemap.xml'), xml, 'utf8');
    log(`public/sitemap.xml written — ${counts.total} URLs (${counts.products} products, ${counts.categories} categories)`);
  }

  // Hand the prerender step the data it needs without fetching twice.
  const cachePath = path.join(ROOT, 'node_modules', '.cache', 'seo');
  fs.mkdirSync(cachePath, { recursive: true });
  fs.writeFileSync(path.join(cachePath, 'catalogue.json'), JSON.stringify({ ...data, origin, defaultImage }), 'utf8');
}

main().catch((error) => {
  warnBlock('SEO PRE-BUILD ERROR', [String(error?.stack || error), 'Continuing the build with the existing SEO assets.']);
  if (STRICT) process.exit(1);
});
